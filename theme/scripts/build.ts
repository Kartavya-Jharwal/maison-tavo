const themeRoot = `${import.meta.dir}/..`;
const banner = '/* Generated by bun run build in theme/. Source: scripts/src. Do not edit. */';

// Project packages/catalog → assets/kansa-catalog.json before bundling the island.
{
  const catalogProc = Bun.spawnSync({
    cmd: ['bun', `${themeRoot}/scripts/build-kansa-catalog.ts`],
    cwd: themeRoot,
    stdout: 'inherit',
    stderr: 'inherit',
  });
  if (catalogProc.exitCode !== 0) {
    console.error('Failed to build kansa-catalog.json');
    process.exit(catalogProc.exitCode ?? 1);
  }
}

const jobs = [
  {
    entry: `${themeRoot}/scripts/src/maison-runtime.js`,
    outfile: `${themeRoot}/assets/maison-runtime.js`,
  },
  {
    entry: `${themeRoot}/scripts/src/lookbook.js`,
    outfile: `${themeRoot}/assets/microapp-lookbook.js`,
  },
  {
    entry: `${themeRoot}/scripts/src/kansa.js`,
    outfile: `${themeRoot}/assets/microapp-kansa.js`,
  },
  {
    entry: `${themeRoot}/scripts/src/vessel.js`,
    outfile: `${themeRoot}/assets/maison-vessel.js`,
  },
  {
    entry: `${themeRoot}/scripts/src/search-assist.js`,
    outfile: `${themeRoot}/assets/maison-search-assist.js`,
  },
  {
    entry: `${themeRoot}/scripts/src/maison-heat.ts`,
    outfile: `${themeRoot}/assets/maison-heat.js`,
  },
  {
    entry: `${themeRoot}/scripts/src/idle-blaze-entry.js`,
    outfile: `${themeRoot}/assets/maison-idle-blaze.js`,
  },
  {
    entry: `${themeRoot}/scripts/src/carousel.js`,
    outfile: `${themeRoot}/assets/maison-carousel.js`,
  },
];

for (const job of jobs) {
  const proc = Bun.spawnSync({
    cmd: [
      'bun',
      'build',
      job.entry,
      `--outfile=${job.outfile}`,
      '--minify',
      '--target=browser',
      '--format=iife',
      '--define',
      'process.env.NODE_ENV="production"',
      `--banner=${banner}`,
    ],
    cwd: themeRoot,
    stdout: 'inherit',
    stderr: 'inherit',
  });

  if (proc.exitCode !== 0) {
    console.error(`Failed to bundle ${job.entry}`);
    process.exit(proc.exitCode ?? 1);
  }
}

console.log(
  'Bundled theme assets: maison-runtime.js, microapp-lookbook.js, microapp-kansa.js, maison-vessel.js, maison-search-assist.js, maison-heat.js, maison-idle-blaze.js, maison-carousel.js',
);
